function isPointInRing(lat, lng, ring) {
	let inside = false;
	for (let i = 0, j = ring.length - 1; i < ring.length; j = i, i += 1) {
		const yi = ring[i][0];
		const xi = ring[i][1];
		const yj = ring[j][0];
		const xj = ring[j][1];
		const crosses = yi > lat !== yj > lat;
		const edgeLng = (xj - xi) * (lat - yi) / (yj - yi || Number.EPSILON) + xi;
		if (crosses && lng < edgeLng) inside = !inside;
	}
	return inside;
}
